#!/bin/bash
# Regenerates src/sgsl_prelude.c (the shared helper text of the shader translator) from src/sgsl_prelude.txt.
# Usage: tests/unit/sgsl/gen_prelude.sh [output.c]
SRC="$(cd "$(dirname "$0")/../../../src" && pwd)"
OUT=${1:-$SRC/sgsl_prelude.c}
case "$OUT" in /*) ;; *) OUT="$PWD/$OUT" ;; esac
{
  echo '// Generated by tests/unit/sgsl/gen_prelude.sh from src/sgsl_prelude.txt - do not edit.'
  echo '#include "sgsl_priv.h"'
  echo 'static const char *const PRELUDE ='
  sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/    "/' -e 's/$/\\n"/' "$SRC/sgsl_prelude.txt"
  echo '    ;'
  echo 'const char *sgsl_prelude_text(void) { return PRELUDE; }'
} > "$OUT"
