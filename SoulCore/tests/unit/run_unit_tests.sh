#!/bin/bash
# Compiles and runs the standalone unit tests (no emulator needed).
cd "$(dirname "$0")" || exit 1
B=../../build/unit
mkdir -p "$B"
python3 inflate_vectors.py "$B/inflate" || { echo "FAIL vector generation"; echo "passed=0 failed=1"; exit 1; }
gcc -std=gnu11 -O2 -Wall -Wextra -I../../src -o "$B/inflate_test" inflate_test.c ../../src/inflate.c || { echo "FAIL build"; echo "passed=0 failed=1"; exit 1; }
"$B/inflate_test" "$B/inflate" | tee "$B/inflate_test.log"
grep -q 'failed=0$' "$B/inflate_test.log" || exit 1

# MSI / CAB reader tests (plain build, then once more under ASan/UBSan when the compiler supports it).
SRCS="msidb_test.c ../../src/msi_db.c ../../src/cab.c ../../src/inflate.c"
gcc -std=gnu11 -O2 -Wall -Wextra -Wno-unused-parameter -D_GNU_SOURCE -I../../src -o "$B/msidb_test" $SRCS || { echo "FAIL msidb build"; echo "passed=0 failed=1"; exit 1; }
"$B/msidb_test" ../msi | tee "$B/msidb_test.log"
grep -q 'failed=0$' "$B/msidb_test.log" || exit 1
echo 'int main(void){return 0;}' > "$B/san_probe.c"
if gcc -fsanitize=address,undefined -o "$B/san_probe" "$B/san_probe.c" 2>/dev/null && "$B/san_probe"; then
    echo "--- msidb_test under -fsanitize=address,undefined"
    gcc -std=gnu11 -O1 -g -fsanitize=address,undefined -fno-sanitize-recover=undefined -Wall -Wextra -Wno-unused-parameter -D_GNU_SOURCE -I../../src -o "$B/msidb_test_asan" $SRCS || { echo "FAIL msidb asan build"; echo "passed=0 failed=1"; exit 1; }
    "$B/msidb_test_asan" ../msi | tee "$B/msidb_test_asan.log"
    grep -q 'failed=0$' "$B/msidb_test_asan.log" || exit 1
else
    echo "(sanitizers unavailable, skipping the ASan run)"
fi

# sgpu software 3D pipeline: pixel-exact scenes (plain build, then under ASan/UBSan when available).
SGSRCS="sgpu_test.c ../../src/sgpu.c"
gcc -std=gnu11 -O2 -Wall -Wextra -Wno-unused-parameter -D_GNU_SOURCE -I../../src -o "$B/sgpu_test" $SGSRCS -lm || { echo "FAIL sgpu build"; echo "passed=0 failed=1"; exit 1; }
"$B/sgpu_test" | tee "$B/sgpu_test.log"
grep -q 'failed=0$' "$B/sgpu_test.log" || exit 1
if gcc -fsanitize=address,undefined -o "$B/san_probe" "$B/san_probe.c" 2>/dev/null && "$B/san_probe"; then
    echo "--- sgpu_test under -fsanitize=address,undefined"
    gcc -std=gnu11 -O1 -g -fsanitize=address,undefined -fno-sanitize-recover=undefined -Wall -Wextra -Wno-unused-parameter -D_GNU_SOURCE -I../../src -o "$B/sgpu_test_asan" $SGSRCS -lm || { echo "FAIL sgpu asan build"; echo "passed=0 failed=1"; exit 1; }
    "$B/sgpu_test_asan" | tee "$B/sgpu_test_asan.log"
    grep -q 'failed=0$' "$B/sgpu_test_asan.log" || exit 1
fi

# Direct3D 9 shader engine (bytecode decoder + interpreter): the token arrays are generated by the
# shader assembler (shaders/d3dasm.py) from shaders/*.asm; the committed header must be up to date.
python3 shaders/d3dasm.py "$B/d3dsh_shaders.h" shaders/vs_1_1.asm shaders/vs_2_0.asm shaders/ps_1_x.asm shaders/ps_2_0.asm || { echo "FAIL d3dsh shader assembly"; echo "passed=0 failed=1"; exit 1; }
cmp -s "$B/d3dsh_shaders.h" shaders/d3dsh_shaders.h || { echo "FAIL shaders/d3dsh_shaders.h is stale (re-run shaders/d3dasm.py)"; echo "passed=0 failed=1"; exit 1; }
D3SRCS="d3dsh_test.c ../../src/d3d9_shader.c ../../src/d3d9_shader_exec.c ../../src/sgpu.c"
gcc -std=gnu11 -O2 -Wall -Wextra -Wno-unused-parameter -D_GNU_SOURCE -I../../src -I. -o "$B/d3dsh_test" $D3SRCS -lm || { echo "FAIL d3dsh build"; echo "passed=0 failed=1"; exit 1; }
"$B/d3dsh_test" | tee "$B/d3dsh_test.log"
grep -q 'failed=0$' "$B/d3dsh_test.log" || exit 1
if gcc -fsanitize=address,undefined -o "$B/san_probe" "$B/san_probe.c" 2>/dev/null && "$B/san_probe"; then
    echo "--- d3dsh_test under -fsanitize=address,undefined"
    gcc -std=gnu11 -O1 -g -fsanitize=address,undefined -fno-sanitize-recover=undefined -Wall -Wextra -Wno-unused-parameter -D_GNU_SOURCE -I../../src -I. -o "$B/d3dsh_test_asan" $D3SRCS -lm || { echo "FAIL d3dsh asan build"; echo "passed=0 failed=1"; exit 1; }
    "$B/d3dsh_test_asan" | tee "$B/d3dsh_test_asan.log"
    grep -q 'failed=0$' "$B/d3dsh_test_asan.log" || exit 1
fi

# sgsl shader translator (GL fixed function / D3D9 texture stages / D3D9 pixel shaders -> MSL and C): the C rendering of
# every configuration is compiled at test time and compared with the CPU implementations; the MSL text is written to
# build/unit/sgsl_msl/*.metal (+ index.txt) for the macOS CI step. The committed prelude must be up to date.
bash sgsl/gen_prelude.sh "$B/sgsl_prelude.c" || { echo "FAIL sgsl prelude generation"; echo "passed=0 failed=1"; exit 1; }
cmp -s "$B/sgsl_prelude.c" ../../src/sgsl_prelude.c || { echo "FAIL src/sgsl_prelude.c is stale (re-run tests/unit/sgsl/gen_prelude.sh)"; echo "passed=0 failed=1"; exit 1; }
SLSRCS="sgsl_test.c ../../src/sgsl.c ../../src/sgsl_ir.c ../../src/sgsl_fe_fix.c ../../src/sgsl_fe_ps.c ../../src/sgsl_prelude.c ../../src/d3d9_shader.c ../../src/d3d9_shader_exec.c"
gcc -std=gnu11 -O2 -Wall -Wextra -Wno-unused-parameter -D_GNU_SOURCE -ffp-contract=off -I../../src -I. -o "$B/sgsl_test" $SLSRCS -lm -ldl || { echo "FAIL sgsl build"; echo "passed=0 failed=1"; exit 1; }
"$B/sgsl_test" | tee "$B/sgsl_test.log"
grep -q 'failed=0$' "$B/sgsl_test.log" || exit 1
if gcc -fsanitize=address,undefined -o "$B/san_probe" "$B/san_probe.c" 2>/dev/null && "$B/san_probe"; then
    echo "--- sgsl_test under -fsanitize=address,undefined"
    gcc -std=gnu11 -O1 -g -fsanitize=address,undefined -fno-sanitize-recover=undefined -Wall -Wextra -Wno-unused-parameter -D_GNU_SOURCE -ffp-contract=off -I../../src -I. -o "$B/sgsl_test_asan" $SLSRCS -lm -ldl || { echo "FAIL sgsl asan build"; echo "passed=0 failed=1"; exit 1; }
    SGSL_SAMPLES=60 SGSL_NO_MOCK=1 ASAN_OPTIONS=detect_leaks=0 "$B/sgsl_test_asan" | tee "$B/sgsl_test_asan.log"
    grep -q 'failed=0$' "$B/sgsl_test_asan.log" || exit 1
fi
