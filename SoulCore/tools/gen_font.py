#!/usr/bin/env python3
"""Rasterises DejaVu Sans (regular + bold) into 4-bit alpha glyph tables for SoulCore's GDI.
Usage: python3 tools/gen_font.py /usr/share/fonts/truetype/dejavu src/gdi_font_data.h
DejaVu fonts: Bitstream Vera / DejaVu license (free to embed and modify)."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_DIR, OUT = sys.argv[1], sys.argv[2]
SIZES = [10, 13, 17, 24, 34]  # em size in pixels
FACES = [("DejaVuSans.ttf", 0), ("DejaVuSans-Bold.ttf", 1), ("DejaVuSansMono.ttf", 2)]  # 2 = monospace
CODES = list(range(32, 127)) + list(range(160, 0x180)) + [0x3C0, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022,
         0x2026, 0x20AC, 0x20BA, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x221A, 0x221E, 0x2260, 0x2264, 0x2265,
         0x232B, 0x25B2, 0x25B6, 0x25BC, 0x25C0, 0x25CF, 0x2713, 0x2715]

data = bytearray()
fonts = []
for fname, bold in FACES:
    for size in SIZES:
        f = ImageFont.truetype(f"{FONT_DIR}/{fname}", size)
        ascent, descent = f.getmetrics()
        glyphs = []
        missing = bytes(f.getmask(chr(0xE000))), f.getbbox(chr(0xE000))
        for cp in CODES:
            ch = chr(cp)
            if cp > 0x17F and (bytes(f.getmask(ch)), f.getbbox(ch)) == missing:
                continue  # not in this font: GDI falls back to '?'

            adv = int(round(f.getlength(ch)))
            bbox = f.getbbox(ch)  # relative to origin at ascent-top
            x0, y0, x1, y1 = bbox
            w, h = max(0, x1 - x0), max(0, y1 - y0)
            off = len(data)
            if w and h:
                img = Image.new("L", (w, h), 0)
                ImageDraw.Draw(img).text((-x0, -y0), ch, font=f, fill=255)
                px = img.tobytes()
                packed = bytearray((w * h + 1) // 2)
                for i, v in enumerate(px):
                    q = (v + 8) // 17
                    if i & 1: packed[i >> 1] |= q << 4
                    else: packed[i >> 1] |= q
                data += packed
            glyphs.append((cp, adv, x0, y0, w, h, off))
        fonts.append((size, bold, ascent, descent, glyphs))

with open(OUT, "w") as o:
    o.write("// Generated by tools/gen_font.py from DejaVu Sans (Bitstream Vera / DejaVu license). Do not edit.\n")
    o.write("#pragma once\n#include <stdint.h>\n")
    o.write("typedef struct { uint16_t cp; uint8_t adv; int8_t x0, y0; uint8_t w, h; uint32_t off; } SoulGlyph;\n")
    o.write("typedef struct { uint8_t size, bold, ascent, descent; uint16_t count; const SoulGlyph *glyphs; } SoulFontFace;\n")
    o.write("static const uint8_t soul_font_bits[%d] = {\n" % len(data))
    for i in range(0, len(data), 24):
        o.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    o.write("};\n")
    for n, (size, bold, asc, desc, glyphs) in enumerate(fonts):
        o.write("static const SoulGlyph soul_glyphs_%d[%d] = {\n" % (n, len(glyphs)))
        for g in glyphs:
            o.write("  {%d,%d,%d,%d,%d,%d,%d},\n" % g)
        o.write("};\n")
    o.write("static const SoulFontFace soul_font_faces[%d] = {\n" % len(fonts))
    for n, (size, bold, asc, desc, glyphs) in enumerate(fonts):
        o.write("  {%d,%d,%d,%d,%d,soul_glyphs_%d},\n" % (size, bold, asc, desc, len(glyphs), n))
    o.write("};\n#define SOUL_FONT_FACE_COUNT %d\n" % len(fonts))
print("glyph bytes:", len(data))
