#!/usr/bin/env python3
"""Generates src/stdcall_args.h: how many bytes of stack arguments each 32-bit Windows
system function removes when it returns (stdcall). The numbers come from the decorated
names (_Name@N) in the i686 MinGW-w64 import libraries. Functions that are not listed
are cdecl (the caller cleans the stack), e.g. the C runtime and wsprintfA."""
import os, re, subprocess, sys

LIBDIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/i686-w64-mingw32/lib"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "stdcall_args.h")
LIBS = """kernel32 ntdll user32 gdi32 advapi32 shell32 ole32 oleaut32 shlwapi ws2_32 wsock32 winmm
comctl32 comdlg32 version imm32 uxtheme dwmapi setupapi bcrypt crypt32 psapi dbghelp winhttp wininet
iphlpapi secur32 userenv rpcrt4 d3d9 d3d11 dxgi opengl32 glu32 xinput1_3 xinput1_4 xinput9_1_0 dsound
dinput8 hid powrprof mpr netapi32 wtsapi32 normaliz cfgmgr32 msimg32 winspool urlmon""".split()

table = {}
for lib in LIBS:
    path = os.path.join(LIBDIR, "lib%s.a" % lib)
    if not os.path.exists(path):
        continue
    out = subprocess.run(["i686-w64-mingw32-nm", path], capture_output=True, text=True).stdout
    for m in re.finditer(r" T _([A-Za-z_][A-Za-z0-9_]*)@(\d+)$", out, re.M):
        name, n = m.group(1), int(m.group(2))
        if name not in table:
            table[name] = n

names = sorted(table)
with open(OUT, "w") as f:
    f.write("// Generated by tools/gen_stdcall.py from the i686 MinGW-w64 import libraries. Do not edit.\n")
    f.write("// Stack argument bytes removed by 32-bit stdcall system functions (sorted for binary search).\n")
    f.write("#pragma once\n#include <stdint.h>\n")
    f.write("typedef struct StdcallArgs { const char *name; uint16_t bytes; } StdcallArgs;\n")
    f.write("static const StdcallArgs k_stdcall_args[] = {\n")
    for n in names:
        f.write('    { "%s", %d },\n' % (n, table[n]))
    f.write("};\n")
    f.write("#define K_STDCALL_ARGS_COUNT %d\n" % len(names))
print("%d functions -> %s" % (len(names), OUT))
