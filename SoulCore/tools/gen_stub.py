#!/usr/bin/env python3
"""Turns a program into a C byte array header: gen_stub.py msiexec.exe src/msiexec_stub.h"""
import sys
data = open(sys.argv[1], "rb").read()
out = ["// generated by tools/gen_stub.py from tools/msiexec/msiexec.exe; do not edit",
       "static const unsigned char k_msiexec_stub[] = {"]
for i in range(0, len(data), 16):
    out.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
out.append("};")
out.append("static const unsigned int k_msiexec_stub_len = %d;" % len(data))
open(sys.argv[2], "w").write("\n".join(out) + "\n")
